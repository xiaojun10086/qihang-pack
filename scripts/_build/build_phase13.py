# ---------------------------------------------------------------- 工具
def rd(p):
    with open(p, 'r', encoding='utf-8') as f:
        return f.read()

def wr(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)

def domain_red_lines(t):
    """从 _domain.md 抽取红线条目（行首锚定，避免命中正文引用）"""
    m = re.search(r'^##\s*⚠️\s*红线[^\n]*$', t, re.M)
    if not m:
        return None
    rest = t[m.end():]
    nxt = re.search(r'^##\s', rest, re.M)
    body = rest[:nxt.start()] if nxt else rest
    return [l.rstrip() for l in body.splitlines() if l.startswith('- ')]

def domain_block(t, header):
    """抽取 _domain.md 某个二级小节的正文（含标题）"""
    m = re.search(r'^##\s*' + re.escape(header) + r'[^\n]*$', t, re.M)
    if not m:
        return None
    rest = t[m.start():]
    nxt = re.search(r'\n##\s', rest[3:], re.M)
    return rest[:3 + nxt.start()].rstrip() if nxt else rest.rstrip()

