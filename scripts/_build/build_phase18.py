# ==================================================================== 0. 修复历史双插（本次自造缺陷）
def repair_double_insert():
    """⚠️ 自造缺陷记录：`§2.1` 的 `new` 里含 `## 3.`，而 16.2 又改了 `§2.1` 内部的表行 ——
    于是第二遍运行时「`new in t`」判据落空、`old`（`## 3.` 标题）仍在 → **整块重复插入**。
    这正是本项目反复记录的「追加型替换 + 完成判据失效」同型缺陷。
    修法：① 本函数把已发生的重复块删掉；② 给相关 `rep` 换成**内容无关的稳定判据**（见各 `already=`）。
    """
    p = 'library/clarity.md'
    t = rd(p)
    dup = detail_block() + '## 3. 判定公式（已修正）'
    if dup in t and t.count('### 2.1 关键槽「已填」的判定细则') > 1:
        wr(p, t.replace(dup, '## 3. 判定公式（已修正）', 1))
        OK.append('%s :: 删除重复插入的 §2.1 块' % p)
    elif t.count('### 2.1 关键槽「已填」的判定细则') > 1:
        MISS.append('%s :: §2.1 重复但无法自动定位删除' % p)
    else:
        DONE.append('%s :: §2.1 无重复插入' % p)


def detail_block():
    """§2.1 的规范文本（与 fix_clarity 中使用的完全一致）。"""
    return _DETAIL


