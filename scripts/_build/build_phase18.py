import os
import re
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')
OK, MISS, DONE = [], [], []


def rd(p):
    with open(os.path.join(ROOT, p), 'r', encoding='utf-8') as f:
        return f.read()


def wr(p, s):
    with open(os.path.join(ROOT, p), 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)


def rep(path, old, new, label='', required=True, already=None):
    """精确替换 + 幂等（完成判据：`already` 或 `new` 已在文本中）。"""
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        MISS.append('%s :: 文件不存在（%s）' % (path, label))
        return
    t = rd(path)
    if (already and already in t) or (new and new in t):
        DONE.append('%s :: %s' % (path, label or old[:26]))
        return
    if old in t:
        wr(path, t.replace(old, new, 1))
        OK.append('%s :: %s' % (path, label or old[:26]))
    elif required:
        MISS.append('%s :: %s' % (path, label or old[:26]))
    else:
        DONE.append('%s :: %s（无需改）' % (path, label or old[:26]))


