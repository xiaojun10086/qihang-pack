# ==================================================================== 15. 版本号 2.9.0 → 2.10.0
def bump_version():
    old, new = '2.9.0', '2.10.0'
    files = ['.codebuddy-plugin/plugin.json', 'library/SKILL.md', 'SKILL.md',
             'PROJECT.md', 'README.md', 'ROADMAP.md', 'qihang-scenario-design.html',
             'scripts/qihang.sh', 'scripts/aligncheck.py', 'references/platforms.md',
             'references/dlut-login-sites.md', 'references/dlut-field-map.md']
    for base, dirs, fs in os.walk(os.path.join(ROOT, 'domains')):
        for fn in fs:
            if fn == 'SKILL.md':
                files.append(os.path.relpath(os.path.join(base, fn), ROOT).replace('\\', '/'))
    n = 0
    for f in files:
        p = os.path.join(ROOT, f)
        if not os.path.exists(p):
            continue
        t = rd(f)
        if old not in t:
            continue
        wr(f, t.replace(old, new))
        n += 1
    if n:
        OK.append('版本号 %s → %s（%d 个文件）' % (old, new, n))
    else:
        DONE.append('版本号（已为 %s）' % new)
    # 版本短写用正则归一化，不依赖上游写的是 v2.8 还是 v2.9
    for path, pat, repl, label in (
        ('config.yaml', r'^# 「启航」学伴包 v[\d.]+ ·', '# 「启航」学伴包 v2.10 ·', 'config.yaml 版本短写'),
        ('PROJECT.md', r'> 版本 v[\d.]+ ｜ (更新 [\d-]+)', r'> 版本 v2.10 ｜ \1', 'PROJECT 版本短写'),
    ):
        t = rd(path)
        t2 = re.sub(pat, repl, t, count=1, flags=re.M)
        if t2 != t:
            wr(path, t2)
            OK.append('%s :: %s' % (path, label))
        else:
            DONE.append('%s :: %s' % (path, label))


